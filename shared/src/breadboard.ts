import type { BoardShape, Part, Pin } from './types';
import { round } from './vec';

const P = 2.54;
export const BREADBOARD_HEIGHT = 8.5;

export type BreadboardSize = 'full' | 'half' | 'mini';

interface Layout {
  name: string;
  columns: number;
  length: number;
  width: number;
  /** Groups of five holes along each power rail. 0 = no rails. */
  railGroups: number;
}

const LAYOUTS: Record<BreadboardSize, Layout> = {
  full: { name: 'Breadboard (full, 830 holes)', columns: 63, length: 165.1, width: 54.6, railGroups: 10 },
  half: { name: 'Breadboard (half, 400 holes)', columns: 30, length: 82, width: 54.6, railGroups: 5 },
  mini: { name: 'Breadboard (mini, 170 holes)', columns: 17, length: 47, width: 35, railGroups: 0 },
};

const ROW_LETTERS = ['a', 'b', 'c', 'd', 'e', 'f', 'g', 'h', 'i', 'j'];
/** Y position of each lettered row, in pitches from the centre line. */
const ROW_Y = [5.5, 4.5, 3.5, 2.5, 1.5, -1.5, -2.5, -3.5, -4.5, -5.5];

const RAILS = [
  { id: 'T+', y: 9.5, color: '#d6392c' },
  { id: 'T-', y: 8.5, color: '#2b62c9' },
  { id: 'B+', y: -8.5, color: '#d6392c' },
  { id: 'B-', y: -9.5, color: '#2b62c9' },
];

export function breadboardId(size: BreadboardSize): string {
  return `builtin:breadboard-${size}`;
}

/** Build a breadboard part: the drawing, every hole, and which holes are joined inside. */
export function makeBreadboard(size: BreadboardSize): Part {
  const L = LAYOUTS[size];
  const H = BREADBOARD_HEIGHT;
  const pins: Pin[] = [];
  const shapes: BoardShape[] = [];

  shapes.push({ kind: 'box', pos: [0, 0, H / 2], size: [L.length, L.width, H], color: '#f1efe6' });
  // Centre channel.
  shapes.push({ kind: 'box', pos: [0, 0, H - 0.4], size: [L.length, 2.6, 1], color: '#cfcbbd' });

  const hole = (x: number, y: number) =>
    shapes.push({ kind: 'box', pos: [x, y, H], size: [1.15, 1.15, 0.12], color: '#3a3a36' });

  for (let c = 1; c <= L.columns; c++) {
    const x = round((c - (L.columns + 1) / 2) * P);
    for (let r = 0; r < ROW_LETTERS.length; r++) {
      const y = round(ROW_Y[r] * P);
      hole(x, y);
      pins.push({
        id: `${ROW_LETTERS[r]}${c}`,
        name: `${ROW_LETTERS[r]}${c}`,
        type: 'OTHER',
        position: [x, y, H],
        normal: [0, 0, 1],
        gender: 'hole',
        group: `col${c}${r < 5 ? 'top' : 'bottom'}`,
      });
    }
  }

  if (L.railGroups > 0) {
    const slots = L.railGroups * 6 - 1;
    for (const rail of RAILS) {
      const y = round(rail.y * P);
      let n = 0;
      for (let s = 0; s < slots; s++) {
        if (s % 6 === 5) continue; // gap between groups of five
        n++;
        const x = round((s - (slots - 1) / 2) * P);
        hole(x, y);
        pins.push({
          id: `${rail.id}${n}`,
          name: `${rail.id}${n}`,
          type: 'OTHER',
          position: [x, y, H],
          normal: [0, 0, 1],
          gender: 'hole',
          group: `rail${rail.id}`,
        });
      }
      // Coloured line beside the rail: outside the outer rail, inside the inner one.
      const isOuter = Math.abs(rail.y) > 9;
      const outward = Math.sign(rail.y) * (isOuter ? 1 : -1);
      shapes.push({
        kind: 'box',
        pos: [0, round(y + outward * 1.5), H],
        size: [slots * P, 0.5, 0.1],
        color: rail.color,
      });
    }
  }

  return {
    id: breadboardId(size),
    name: L.name,
    category: 'Breadboard',
    model: { kind: 'board', spec: { shapes } },
    builtin: true,
    isBreadboard: true,
    logicVoltage: 5,
    bbox: { min: [-L.length / 2, -L.width / 2, 0], max: [L.length / 2, L.width / 2, H] },
    pins,
    strips: [],
    note: 'Generated by the app. Holes in a column and along a power rail are connected inside.',
  };
}
